-- «Больше не предлагать резюме для этой встречи».
-- Кнопка массового создания резюме показывает встречи без резюме; те, что
-- пользователь пометил как ненужные, сюда и попадают - и больше не предлагаются.
-- 0 = предлагать (по умолчанию), 1 = скрыть из предложений.
ALTER TABLE meetings ADD COLUMN summary_opt_out INTEGER NOT NULL DEFAULT 0;
