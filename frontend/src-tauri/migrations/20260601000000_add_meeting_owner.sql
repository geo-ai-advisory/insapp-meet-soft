-- Migration: привязка встреч к учётной записи (изоляция локального кэша)
--
-- Раньше все локальные встречи были общими: при входе под любой учёткой
-- показывались все записи на компьютере. Теперь у встречи есть владелец
-- (owner_login = логин учётки). Список фильтруется по текущей залогиненной
-- учётке: ivan видит только свои, geom - только свои.
--
-- Существующие встречи (созданы до системы учёток) привязываем к 'geom' -
-- основному пользователю, под которым они и записывались. Под другими
-- учётками (ivan и т.д.) старые встречи geom уже не появятся.
ALTER TABLE meetings ADD COLUMN owner_login TEXT;
UPDATE meetings SET owner_login = 'geom' WHERE owner_login IS NULL OR owner_login = '';
